-- 002: أمان الجلسات (إضافي فقط — لا يحذف ولا يعدّل أي بيانات موجودة)
-- session_version: يُرفع عند تغيير كلمة المرور أو إعادة تعيينها أو إيقاف الحساب/فصله،
-- فتصبح كل الجلسات (JWT) الصادرة قبل ذلك غير صالحة فورًا.
-- القيمة الافتراضية 0 تطابق الجلسات الحالية (التي لا تحمل رقم إصدار)، فلا يُسجَّل خروج أحد عند النشر.
alter table users add column if not exists session_version integer not null default 0;
